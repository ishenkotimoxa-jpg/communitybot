def faq_menu(category_id: str | None = None, question_id: str | None = None) -> InlineKeyboardMarkup:
    rows = []
    if category_id is None:
        rows.extend([
            InlineKeyboardButton(text=category["title"], callback_data=f"faq_category:{key}")
        ] for key, category in FAQ_CATEGORIES.items())
    elif question_id is None:
        rows.extend([
            InlineKeyboardButton(text=question[0], callback_data=f"faq_answer:{category_id}:{key}")
        ] for key, question in FAQ_CATEGORIES[category_id]["questions"].items())
    else:
        source = FAQ_CATEGORIES[category_id].get("source")
        if source:
            rows.append([InlineKeyboardButton(text="🔗 Подробнее на сайте МИФИ", url=source)])
        rows.append([InlineKeyboardButton(text="⬅️ К вопросам темы", callback_data=f"faq_category:{category_id}")])
    rows.append([InlineKeyboardButton(text="✍️ Задать вопрос", callback_data="ask_question")])
    if category_id is not None:
        rows.append([InlineKeyboardButton(text="⬅️ Категории вопросов", callback_data="faq")])
    rows.append([InlineKeyboardButton(text="⬅️ Главное меню", callback_data="back_to_main")])
    return InlineKeyboardMarkup(inline_keyboard=rows)
